export function computeDerivedStats(char: CharacterDoc, hasPriestessBuff = false): DerivedStats {
  const equippedIds = [
    char.equippedWeapon,
    char.equippedHelm,
    char.equippedArmor,
    char.equippedGloves,
    char.equippedPants,
    char.equippedBoots,
    char.equippedRing,
    char.equippedWings,
    ...(char.mounted ? [char.equippedMount] : []),
  ];

  let gearAtk = 0;
  let gearDef = 0;
  let gearHp = 0;
  let gearMp = 0;
  let gearCrit = 0;
  let gearMovePct = 0;

  for (const id of equippedIds) {
    const item = ITEMS_CATALOG[id];
    if (!item) continue;
    gearAtk += item.atk;
    gearDef += item.def;
    gearHp += item.hp;
    gearMp += item.mp;
    gearCrit += item.critPct;
    gearMovePct += item.moveSpdPct;
  }

  const enhMult =
    1 + char.enhanceLevel * 0.08 + (char.enhanceLevel >= 9 ? (char.enhanceLevel - 8) * 0.06 : 0);
  let setBonusLabel = 'Chưa kích hoạt Hào Quang Cường Hoá (Cần +7)';
  if (char.enhanceLevel >= 15) {
    setBonusLabel = 'Hào Quang Thần Thoại +15 (Tất cả chỉ số Trang Bị +162%)';
  } else if (char.enhanceLevel >= 13) {
    setBonusLabel = 'Hào Quang Huyết Tinh +13 (Tất cả chỉ số Trang Bị +134%)';
  } else if (char.enhanceLevel >= 11) {
    setBonusLabel = 'Hào Quang Hoàng Kim +11 (Tất cả chỉ số Trang Bị +106%)';
  } else if (char.enhanceLevel >= 9) {
    setBonusLabel = 'Hào Quang Tinh Anh +9 (Tất cả chỉ số Trang Bị +78%)';
  } else if (char.enhanceLevel >= 7) {
    setBonusLabel = 'Hào Quang Kim Loại Sáng +7 (Tất cả chỉ số Trang Bị +56%)';
  }

  const totalGearAtk = Math.round(gearAtk * enhMult);
  const totalGearDef = Math.round(gearDef * enhMult);
  const totalGearHp = Math.round(gearHp * enhMult);
  const totalGearMp = Math.round(gearMp * enhMult);

  let primaryAttrAtk = 0;
  if (char.classId === 'esper') {
    primaryAttrAtk = char.ene * 2.4 + char.str * 0.6;
  } else if (char.classId === 'vanguard') {
    primaryAttrAtk = char.str * 2.5 + char.ene * 0.5;
  } else {
    primaryAttrAtk = char.agi * 2.1 + char.str * 1.1;
  }

  const buffAtkDefMult = hasPriestessBuff ? 1.2 : 1.0;
  const buffHpMult = hasPriestessBuff ? 1.15 : 1.0;

  const baseAtk = Math.round((24 + char.level * 9 + primaryAttrAtk + totalGearAtk) * buffAtkDefMult);
  const atkMin = Math.max(14, Math.round(baseAtk * 0.88));
  const atkMax = Math.max(20, Math.round(baseAtk * 1.16));

  const maxHp = Math.round((340 + char.level * 48 + char.vit * 18 + totalGearHp) * buffHpMult);
  const maxMp = Math.round(130 + char.level * 18 + char.ene * 12 + totalGearMp);
  const defense = Math.round(
    (22 + char.level * 4 + char.agi * 0.9 + char.vit * 0.7 + totalGearDef) * buffAtkDefMult
  );
  const critRate = Math.min(85, Math.round((5 + char.agi * 0.08 + gearCrit) * 10) / 10);
  const critDmg = Math.round(150 + char.enhanceLevel * 6 + char.ene * 0.15);
  const atkSpeed = Math.round(100 + char.agi * 0.45);
  const evasion = Math.round(char.agi * 1.3 + char.level * 2);
  const moveSpeed = Math.round(100 + gearMovePct + (hasPriestessBuff ? 8 : 0));

  const combatPower = Math.round(
    atkMax * 4.2 +
      defense * 2.8 +
      maxHp * 0.35 +
      maxMp * 0.12 +
      critRate * 28 +
      char.enhanceLevel * 220
  );

  return {
    combatPower,
    maxHp,
    maxMp,
    atkMin,
    atkMax,
    defense,
    critRate,
    critDmg,
    atkSpeed,
    evasion,
    moveSpeed,
    setBonusLabel: hasPriestessBuff ? `[Chúc Phúc +20%] · ${setBonusLabel}` : setBonusLabel,
  };
}

